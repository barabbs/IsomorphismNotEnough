"""Redact the solution-bearing fields of the run records, replacing each one
with a SHA-256 commitment to its original value.

    digest(v) = "sha256:" + hex(SHA-256(UTF-8(
        json.dumps(v, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    )))

where v is the field's original JSON value (string, list or object).

Redacted fields of each data/<stack>/clever/<TASK>/<record>.json:
  - solution
  - metadata.<stack>                     (full agent trace)
  - metadata.result                      (final agent reply)
  - metadata.validation[].lean_code
  - metadata.validation[].error_message
  - text, for SPEC_ISO*, IMPL_GEN_GEN* and PROOF_GEN_GEN* (these inputs embed
    specifications and implementations generated by the agents upstream)

Usage:
    python scripts/redact.py redact ORIG_DATA_DIR OUT_DATA_DIR
    python scripts/redact.py verify ORIG_DATA_DIR REDACTED_DATA_DIR
"""
import hashlib
import json
import sys
from pathlib import Path

STACKS = {"claude", "codex", "kimi", "codex-pre"}
TEXT_REVEALING = ("SPEC_ISO", "IMPL_GEN_GEN", "PROOF_GEN_GEN")
FORMATS = ({"indent": 2, "ensure_ascii": False}, {"indent": 2})


def digest(v):
    s = json.dumps(v, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    return "sha256:" + hashlib.sha256(s.encode("utf-8")).hexdigest()


def redact(d, task):
    if task.startswith(TEXT_REVEALING):
        d["text"] = digest(d["text"])
    d["solution"] = digest(d["solution"])
    m = d["metadata"]
    for k in m.keys() & STACKS:
        m[k] = digest(m[k])
    if "result" in m:
        m["result"] = digest(m["result"])
    for v in m.get("validation") or []:
        v["lean_code"] = digest(v["lean_code"])
        v["error_message"] = digest(v["error_message"])
    return d


def records(root):
    return sorted(Path(root).glob("*/clever/*/*.json"))


def redact_all(src, dst):
    src, dst = Path(src), Path(dst)
    for f in records(src):
        raw = f.read_text(encoding="utf-8")
        d = json.loads(raw)
        # keep the original serialization of the untouched fields
        kw = next((kw for kw in FORMATS if json.dumps(d, **kw) == raw.rstrip("\n")), FORMATS[0])
        out = dst / f.relative_to(src)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(json.dumps(redact(d, f.parent.name), **kw) + raw[len(raw.rstrip("\n")):],
                       encoding="utf-8")


def verify_all(orig, redacted):
    orig, redacted = Path(orig), Path(redacted)
    bad = 0
    files = records(orig)
    for f in files:
        expected = redact(json.loads(f.read_text(encoding="utf-8")), f.parent.name)
        g = redacted / f.relative_to(orig)
        if not g.exists() or json.loads(g.read_text(encoding="utf-8")) != expected:
            bad += 1
            print(f"MISMATCH {f.relative_to(orig)}")
    print(f"{len(files) - bad}/{len(files)} records match")
    return bad == 0


if __name__ == "__main__":
    if len(sys.argv) != 4 or sys.argv[1] not in ("redact", "verify"):
        sys.exit(__doc__)
    if sys.argv[1] == "redact":
        redact_all(sys.argv[2], sys.argv[3])
    else:
        sys.exit(0 if verify_all(sys.argv[2], sys.argv[3]) else 1)
